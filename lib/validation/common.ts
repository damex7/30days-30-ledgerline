import { z } from "zod";
import { parseNaira } from "@/lib/money";
import { isIsoDate } from "@/lib/dates";

// Building blocks shared by every form, route handler and AI schema.

export const uuid = z.uuid({ error: "Invalid id." });

/** Trimmed, required text with a length cap. */
export const text = (max: number, label = "This field") =>
  z
    .string({ error: `${label} is required.` })
    .trim()
    .min(1, `${label} is required.`)
    .max(max, `${label} must be at most ${max} characters.`);

/** Optional text: an empty field becomes null. */
export const optionalText = (max: number, label = "This field") =>
  z
    .string()
    .trim()
    .max(max, `${label} must be at most ${max} characters.`)
    .optional()
    .transform((v) => (v ? v : null));

export const email = z.string().trim().toLowerCase().pipe(z.email({ error: "Enter a valid email address." }).max(254));

export const optionalEmail = z
  .string()
  .trim()
  .toLowerCase()
  .optional()
  .transform((v) => v || null)
  .pipe(z.email({ error: "Enter a valid email address." }).max(254).nullable());

/** Nigerian-style phone numbers: digits, spaces and an optional leading +. */
export const optionalPhone = z
  .string()
  .trim()
  .optional()
  .transform((v) => (v ? v.replace(/[-()]/g, "").replace(/\s+/g, " ") : null))
  .pipe(
    z
      .string()
      .regex(/^\+?[0-9][0-9 ]{6,19}$/, "Enter a phone number like 0803 123 4567 or +234 803 123 4567.")
      .nullable(),
  );

/** A naira amount typed by a person -> integer kobo (see lib/money.ts). */
export const nairaInput = (label = "Amount") =>
  z.string({ error: `${label} is required.` }).transform((value, ctx) => {
    const parsed = parseNaira(value);
    if (!parsed.ok) {
      ctx.addIssue({ code: "custom", message: parsed.error });
      return z.NEVER;
    }
    return parsed.kobo;
  });

/** Same, but empty means 0 (discount, delivery fee). */
export const optionalNairaInput = (label = "Amount") =>
  z
    .string()
    .optional()
    .transform((value, ctx) => {
      if (!value || !value.trim()) return 0;
      const parsed = parseNaira(value);
      if (!parsed.ok) {
        ctx.addIssue({ code: "custom", message: `${label}: ${parsed.error}` });
        return z.NEVER;
      }
      return parsed.kobo;
    });

/** Integer kobo in JSON bodies and AI output. */
export const kobo = z.number().int("Amounts must be whole kobo.").min(0).max(1_000_000_000_000);
export const positiveKobo = kobo.min(1, "Amount must be more than ₦0.");

export const isoDate = z.string().refine(isIsoDate, "Enter a valid date.");

/** Whole units. */
export const quantity = z.coerce
  .number({ error: "Enter a quantity." })
  .int("Quantities are whole numbers.")
  .min(1, "Quantity must be at least 1.")
  .max(100_000, "That quantity is too large.");

/** Idempotency key generated by the browser for every create. */
export const clientRequestId = z.uuid({ error: "Missing request id; reload the page and try again." });
